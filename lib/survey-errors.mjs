// Do not display database messages: they may contain identifiers or personal data.
export function surveyErrorMessage(error) {
  const code = String(error?.code || '');
  if (code === '23505') return 'มีข้อมูลรายการนี้อยู่แล้ว กรุณาค้นหาและตรวจสอบรายการเดิมก่อนบันทึก';
  if (code === '42501') return 'บัญชีนี้ไม่มีสิทธิ์ดำเนินการ กรุณาติดต่อเจ้าหน้าที่ผู้ดูแลระบบ';
  if (['PGRST301', 'PGRST302', '28000'].includes(code)) return 'การเข้าสู่ระบบหมดอายุ กรุณาเข้าสู่ระบบใหม่แล้วลองอีกครั้ง';
  if (['42703', '42P01', 'PGRST204', 'PGRST205'].includes(code)) return 'ระบบยังไม่พร้อมบันทึกข้อมูลส่วนนี้ กรุณาแจ้งผู้ดูแลระบบให้ปรับปรุงฐานข้อมูล';
  if (code === '23503') return 'ไม่พบข้อมูลที่รายการนี้อ้างอิง กรุณาโหลดข้อมูลใหม่แล้วตรวจสอบอีกครั้ง';
  if (['23502', '23514', '22P02', '22007'].includes(code)) return 'ข้อมูลบางช่องไม่ครบหรือรูปแบบไม่ถูกต้อง กรุณาตรวจสอบก่อนบันทึกอีกครั้ง';
  if (/fetch|network|connection|timeout/i.test(error?.message || '') || code === '57014') return 'เชื่อมต่อไม่สำเร็จหรือใช้เวลานาน กรุณาตรวจสอบอินเทอร์เน็ตแล้วลองอีกครั้ง';
  return 'ดำเนินการไม่สำเร็จ กรุณาลองอีกครั้ง หากยังพบปัญหาให้แจ้งผู้ดูแลระบบ';
}
